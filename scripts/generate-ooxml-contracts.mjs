import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';

const documents = [
  ['OOXML_PARTS_CSV', '../docs/HANS-SAFEDOC-V1.1-OOXML-ALLOWLIST.csv'],
  ['OOXML_RELATIONSHIPS_CSV', '../docs/HANS-SAFEDOC-V1.1-OOXML-RELATIONSHIPS.csv'],
  ['OOXML_SURFACES_CSV', '../docs/HANS-SAFEDOC-V1.1-OOXML-SURFACES.csv'],
];
const loaded = await Promise.all(
  documents.map(async ([name, relative]) => ({
    name,
    source: await readFile(new URL(relative, import.meta.url), 'utf8'),
  })),
);
const sha256 = createHash('sha256')
  .update(loaded.map((item) => item.source).join('\u0000'), 'utf8')
  .digest('hex');
const outputPath = new URL(
  '../packages/document-formats/src/ooxml/generated-contracts.ts',
  import.meta.url,
);
const prettierConfig = (await resolveConfig(outputPath)) ?? {};
const output = await format(
  `// Generated by scripts/generate-ooxml-contracts.mjs; do not edit.\n${loaded
    .map((item) => `export const ${item.name} = ${JSON.stringify(item.source)} as const;`)
    .join('\n')}\nexport const OOXML_CONTRACTS_SOURCE_SHA256 = '${sha256}' as const;\n`,
  { ...prettierConfig, parser: 'typescript' },
);
await writeFile(outputPath, output, 'utf8');
